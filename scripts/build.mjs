import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../extension/', import.meta.url);
const routing = (await readFile(new URL('routing.js', root), 'utf8')).replace(/^export /gm, '');
const background = (await readFile(new URL('background.js', root), 'utf8')).replace(/^import .*;\n/, '');
const suggestions = (await readFile(new URL('suggestions.js', root), 'utf8')).replace(/^export /gm, '');
const learning = (await readFile(new URL('learning-background.js', root), 'utf8')).replace(/^import .*;\n/, '');
const generated = `// Generated by npm run build.\n(() => {\n${routing}\n${background}\n${suggestions}\n${learning}\n})();\n`;

const bundle = new URL('background.bundle.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(bundle, 'utf8') !== generated) {
    console.error('background.bundle.js is stale; run npm run build and commit the generated bundle.');
    process.exitCode = 1;
  }
} else {
  await writeFile(bundle, generated);
}
